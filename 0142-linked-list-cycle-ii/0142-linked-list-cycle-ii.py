# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, x):
#         self.val = x
#         self.next = None

class Solution:
    def detectCycle(self, head: Optional[ListNode]) -> Optional[ListNode]:
        arr=set()
        count=0
        temp=head
        while(temp is not None):
            if temp in arr:
                return temp
            arr.add(temp)
            temp=temp.next
        return None
        

